// defaultQuotaForUsd converts a USD amount to internal quota units using the
// configured quota-per-unit exchange rate, so default prizes carry the same
// real-world value whether the admin edits them in USD or they are seeded.
func defaultQuotaForUsd(usd float64) int {
	return common.QuotaFromFloat(usd * common.QuotaPerUnit)
}

func initializeLotteryPrizes() error {
	// Insert any missing default prizes and refresh only the display label. The
	// credited quota_amount is intentionally NOT updated on conflict so that any
	// amount the admin has configured is never overwritten by the defaults.
	// Name, weight, active and sorting are also left untouched.
	err := DB.Clauses(clause.OnConflict{
		Columns:   []clause.Column{{Name: "code"}},
		DoUpdates: clause.AssignmentColumns([]string{"label"}),
	}).Create(&defaultLotteryPrizes).Error
	if err != nil {
		return err
	}

	// The legacy "retry" lucky-charm prize (redeem for another draw) is no
	// longer part of the lottery and should be removed from the board.
	return DB.Where("code = ?", "retry").Delete(&LotteryPrize{}).Error
}

func LotteryBusinessDay(now time.Time) string {
	return now.In(shanghaiLocation).Format("2006-01-02")
}

func GetActiveLotteryPrizes() ([]LotteryPrize, error) {
	var prizes []LotteryPrize
	err := DB.Where("active = ? AND weight > ?", true, 0).Order("sort_order ASC").Find(&prizes).Error
	return prizes, err
}

func HasLotteryDrawn(userId int, drawDay string) (bool, error) {
	var count int64
	err := DB.Model(&LotteryDrawRecord{}).
		Where("user_id = ? AND draw_day = ?", userId, drawDay).
		Count(&count).Error
	return count > 0, err
}

func CreateLotteryDrawRecord(record *LotteryDrawRecord) error {
	err := DB.Create(record).Error
	if err == nil {
		return nil
	}

	drawn, lookupErr := HasLotteryDrawn(record.UserId, record.DrawDay)
	if lookupErr == nil && drawn {
		return ErrLotteryDailyLimitReached
	}
	return err
}

// CreateLotteryDrawRecordTx atomically inserts a draw record and credits the
// winner's quota inside a single transaction. The check for an existing draw on
// the same business day runs inside the transaction so concurrent draws are
// serialized by the database. If quotaToAdd is positive, it is added to the
// user's quota in the same transaction; a failure in either step rolls back the
// whole operation so a record is never written without its quota being credited
// (and vice versa).
func CreateLotteryDrawRecordTx(userId int, drawDay string, record *LotteryDrawRecord, quotaToAdd int) error {
	err := DB.Transaction(func(tx *gorm.DB) error {
		var count int64
		if err := tx.Model(&LotteryDrawRecord{}).
			Where("user_id = ? AND draw_day = ?", userId, drawDay).
			Count(&count).Error; err != nil {
			return err
		}
		if count > 0 {
			return ErrLotteryDailyLimitReached
		}
		if err := tx.Create(record).Error; err != nil {
			return err
		}
		if quotaToAdd > 0 {
			if err := tx.Model(&User{}).
				Where("id = ?", userId).
				Update("quota", gorm.Expr("quota + ?", quotaToAdd)).Error; err != nil {
				return err
			}
		}
		return nil
	})
	if err != nil {
		return err
	}
	// The DB write and quota credit are committed atomically; only now do we
	// sync the in-memory/Redis quota cache so the user sees the credited amount
	// immediately. A cache failure does not roll back the committed draw.
	if quotaToAdd > 0 {
		if err := cacheIncrUserQuota(userId, int64(quotaToAdd)); err != nil {
			common.SysLog("failed to increase user quota cache after lottery draw: " + err.Error())
		}
	}
	return nil
}

// GetLotteryDrawRecords returns today's draw records ordered by the credited
// quota descending (so the highest win appears first), falling back to the
// newest draw for equal amounts. It returns all rows for the day.
func GetLotteryDrawRecords(drawDay string) ([]LotteryDrawRecord, error) {
	var records []LotteryDrawRecord
	err := DB.Where("draw_day = ?", drawDay).
		Order("quota_amount DESC, created_at DESC").
		Limit(20).
		Find(&records).Error
	return records, err
}

// GetUserLotteryDrawRecords returns the user's draw records ordered by draw
// time descending. The limit caps the returned rows so the history view can
// scroll within a fixed-height panel.
func GetUserLotteryDrawRecords(userId int, limit int) ([]LotteryDrawRecord, error) {
	var records []LotteryDrawRecord
	err := DB.Where("user_id = ?", userId).
		Order("created_at DESC").
		Limit(limit).
		Find(&records).Error
	return records, err
}

// GetTodayUserDraw returns the user's draw record for the given business day.
// It returns nil when the user has not drawn yet on that day.
func GetTodayUserDraw(userId int, drawDay string) (*LotteryDrawRecord, error) {
	var record LotteryDrawRecord
	err := DB.Where("user_id = ? AND draw_day = ?", userId, drawDay).
		Order("created_at DESC").
		First(&record).Error
	if err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return nil, nil
		}
		return nil, err
	}
	return &record, nil
}

// GetAllLotteryPrizes returns all configured prizes ordered by their board
// position, including inactive ones, for the admin management page.
func GetAllLotteryPrizes() ([]LotteryPrize, error) {
	var prizes []LotteryPrize
	err := DB.Order("sort_order ASC").Find(&prizes).Error
	return prizes, err
}

