var ErrLotteryDailyLimitReached = errors.New("lottery daily limit reached")

// LotteryPrize stores one configurable prize shown on the eight-cell lottery board.
type LotteryPrize struct {
	Id         int       `json:"id" gorm:"primaryKey;autoIncrement"`                             // Primary key generated by the database.
	Code       string    `json:"code" gorm:"type:varchar(32);uniqueIndex;not null"`              // Stable prize code used by API clients and historical snapshots.
	Name       string    `json:"name" gorm:"type:varchar(64);not null"`                          // Display name of the prize tier.
	Label      string    `json:"label" gorm:"type:varchar(128);not null"`                        // User-facing description of the reward.
	Icon       string    `json:"icon" gorm:"type:varchar(16);not null"`                          // Short symbol or number rendered inside the lottery cell.
	Tone       string    `json:"tone" gorm:"type:varchar(16);not null"`                          // Visual tone identifier understood by the frontend.
	Weight      int       `json:"weight" gorm:"not null"`                                         // Positive relative probability weight used for server-side selection.
	QuotaAmount int       `json:"quota_amount" gorm:"not null;default:0"`                         // Quota value credited to the winner's balance when this prize is drawn; 0 means no quota is credited.
	SortOrder  int       `json:"sort_order" gorm:"index:idx_lottery_prize_active_sort;not null"` // One-based position on the eight-cell board.
	Active     bool      `json:"active" gorm:"index:idx_lottery_prize_active_sort;not null"`     // Whether this prize participates in draws.
	CreatedAt  time.Time `json:"created_at" gorm:"not null"`                                     // Time when the prize configuration was created.
	UpdatedAt  time.Time `json:"updated_at" gorm:"not null"`                                     // Time when the prize configuration was last changed.
}

func (LotteryPrize) TableName() string {
	return "lottery_prizes"
}

// LotteryDrawRecord stores the immutable result of one user's daily draw.
type LotteryDrawRecord struct {
	Id          int64     `json:"id" gorm:"primaryKey;autoIncrement"`                                                    // Primary key generated by the database.
	UserId      int       `json:"user_id" gorm:"uniqueIndex:idx_lottery_draw_user_day;not null"`                         // Authenticated New API user ID, unique together with DrawDay.
	DrawDay     string    `json:"draw_day" gorm:"type:varchar(10);uniqueIndex:idx_lottery_draw_user_day;index;not null"` // Business date in YYYY-MM-DD format using Asia/Shanghai.
	DisplayName string    `json:"display_name" gorm:"type:varchar(128);not null"`                                        // Masked username snapshot safe for the public activity list.
	PrizeCode   string    `json:"prize_code" gorm:"type:varchar(32);not null"`                                           // Prize code snapshot at draw time.
	PrizeName   string    `json:"prize_name" gorm:"type:varchar(64);not null"`                                           // Prize tier name snapshot at draw time.
	PrizeLabel  string    `json:"prize_label" gorm:"type:varchar(128);not null"`                                         // Prize reward description snapshot at draw time.
	QuotaAmount int       `json:"quota_amount" gorm:"not null;default:0"`                                                 // Quota value snapshot credited to the user at draw time; 0 means no quota.
	CreatedAt   time.Time `json:"created_at" gorm:"index;not null"`                                                      // UTC-backed timestamp when the draw was recorded.
}

func (LotteryDrawRecord) TableName() string {
	return "draw_records"
}

