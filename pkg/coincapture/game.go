package coincapture

import (
	"crypto/rand"
	"encoding/binary"
	"errors"
	"math"
)

const (
	Width      = 900
	Height     = 540
	DurationMS = 40_000
	MaxScore   = 9999
	StepMS     = 20
)

type Player struct {
	X   float64 `json:"x"`
	Y   float64 `json:"y"`
	TX  float64 `json:"tx"`
	TY  float64 `json:"ty"`
	R   float64 `json:"r"`
	Inv float64 `json:"inv"`
}

type Coin struct {
	X     float64 `json:"x"`
	Y     float64 `json:"y"`
	Value int     `json:"value"`
	R     float64 `json:"r"`
	Phase float64 `json:"phase"`
	Alive bool    `json:"alive"`
}

type Item struct {
	X     float64 `json:"x"`
	Y     float64 `json:"y"`
	R     float64 `json:"r"`
	Type  string  `json:"type"`
	Phase float64 `json:"phase"`
	Life  float64 `json:"life"`
	Gone  bool    `json:"gone"`
}

type Patrol struct {
	X      float64 `json:"x"`
	Y      float64 `json:"y"`
	R      float64 `json:"r"`
	Axis   string  `json:"axis"`
	Center float64 `json:"center"`
	Range  float64 `json:"range"`
	Speed  float64 `json:"speed"`
	Phase  float64 `json:"phase"`
}

// Movement records a target change at a fixed simulation tick, not a score.
type Movement struct {
	ElapsedMS int64   `json:"elapsed_ms"`
	X         float64 `json:"x"`
	Y         float64 `json:"y"`
}

// Game is generated by the server and replayed at settlement. The client can
// submit timed movement targets, but never supplies a trusted score or seed.
type Game struct {
	RandomState    uint32   `json:"randomState"`
	Player         Player   `json:"player"`
	Coins          []Coin   `json:"coins"`
	Items          []Item   `json:"items"`
	Patrols        []Patrol `json:"patrols"`
	Score          int      `json:"score"`
	CoinsCollected int      `json:"coinsCollected"`
	ElapsedMS      int64    `json:"elapsedMs"`
	Combo          int      `json:"combo"`
	ComboUntil     int64    `json:"comboUntil"`
	MagnetT        float64  `json:"magnetT"`
	SmokeT         float64  `json:"smokeT"`
	MultT          float64  `json:"multT"`
	CaughtT        float64  `json:"caughtT"`
	Notice         string   `json:"notice"`
	NoticeT        float64  `json:"noticeT"`
	NoticePoints   int      `json:"noticePoints"`
	SpawnAt        int64    `json:"spawnAt"`
	ItemAt         int64    `json:"itemAt"`
}

func (game *Game) randomBetween(low, high float64) float64 {
	game.RandomState ^= game.RandomState << 13
	game.RandomState ^= game.RandomState >> 17
	game.RandomState ^= game.RandomState << 5
	unit := float64(game.RandomState) / 4294967296
	return low + unit*(high-low)
}

func NewGame() *Game {
	var data [4]byte
	_, _ = rand.Read(data[:])
	seed := binary.BigEndian.Uint32(data[:])
	if seed == 0 {
		seed = 0x6d2b79f5
	}
	game := &Game{
		RandomState: seed,
		Player:      Player{X: 450, Y: 270, TX: 450, TY: 270, R: 12},
		Coins:       make([]Coin, 0, 48), Items: []Item{},
		Patrols: []Patrol{
			{X: 170, Y: 145, R: 15, Axis: "x", Center: 450, Range: 340, Speed: .78},
			{X: 432, Y: 390, R: 15, Axis: "y", Center: 270, Range: 205, Speed: 1.04, Phase: 2.1},
			{X: 450, Y: 373, R: 13, Axis: "x", Center: 450, Range: 220, Speed: .57, Phase: 4},
		},
		SpawnAt: 1160,
	}
	game.ItemAt = int64(game.randomBetween(7000, 11000))
	for row := range 4 {
		for column := range 8 {
			game.addCoin(80+float64(column)*105+game.randomBetween(-12, 12), 75+float64(row)*120+game.randomBetween(-13, 13))
		}
	}
	return game
}

func (game *Game) addCoin(x, y float64) {
	coin := Coin{X: x, Y: y, Value: 1, R: 9, Phase: game.randomBetween(0, 7), Alive: true}
	if game.randomBetween(0, 1) < .13 {
		coin.Value, coin.R = 3, 12
	}
	game.Coins = append(game.Coins, coin)
}

func (game *Game) Multiplier() float64 {
	if game.MultT > 0 {
		return 2
	}
	if game.Combo >= 20 {
		return 3
	}
	if game.Combo >= 10 {
		return 2
	}
	if game.Combo >= 5 {
		return 1.5
	}
	return 1
}

func (game *Game) SetTarget(x, y float64) {
	game.Player.TX = max(27, min(Width-27, x))
	game.Player.TY = max(27, min(Height-27, y))
}

// Replay verifies a bounded, chronological input history and derives the
// result from the stored initial state. Supplied times never extend the round.
func (game *Game) Replay(movements []Movement) error {
	if len(movements) > DurationMS/StepMS {
		return errors.New("too many game movements")
	}
	previous := game.ElapsedMS - 1
	for _, movement := range movements {
		if movement.ElapsedMS <= previous || movement.ElapsedMS < game.ElapsedMS ||
			movement.ElapsedMS >= DurationMS || movement.ElapsedMS%StepMS != 0 ||
			math.IsNaN(movement.X) || math.IsInf(movement.X, 0) ||
			math.IsNaN(movement.Y) || math.IsInf(movement.Y, 0) ||
			movement.X < 27 || movement.X > Width-27 || movement.Y < 27 || movement.Y > Height-27 {
			return errors.New("invalid game movement history")
		}
		previous = movement.ElapsedMS
	}
	if game.RandomState == 0 {
		game.RandomState = 0x6d2b79f5
	}
	for _, movement := range movements {
		game.Advance(movement.ElapsedMS)
		game.SetTarget(movement.X, movement.Y)
	}
	game.Advance(DurationMS)
	return nil
}

// Advance uses server elapsed time and fixed-size movement steps. Faster input
// traffic never increases movement speed, creates coins or extends the round.
func (game *Game) Advance(elapsedMS int64) {
	limit := min(int64(DurationMS), max(0, elapsedMS))
	for game.ElapsedMS+StepMS <= limit {
		game.ElapsedMS += StepMS
		game.step()
	}
}

func (game *Game) step() {
	const dt = float64(StepMS) / 1000
	game.MagnetT = max(0, game.MagnetT-dt)
	game.SmokeT = max(0, game.SmokeT-dt)
	game.MultT = max(0, game.MultT-dt)
	game.CaughtT = max(0, game.CaughtT-dt)
	game.NoticeT = max(0, game.NoticeT-dt)
	game.Player.Inv = max(0, game.Player.Inv-dt)
	if game.ElapsedMS > game.ComboUntil {
		game.Combo = 0
	}
	dx, dy := game.Player.TX-game.Player.X, game.Player.TY-game.Player.Y
	distance := math.Hypot(dx, dy)
	if distance > 1 {
		travel := min(distance, 480*dt)
		game.Player.X += dx / distance * travel
		game.Player.Y += dy / distance * travel
	}
	if game.ElapsedMS >= game.SpawnAt && len(game.Coins) < 48 {
		game.SpawnAt = game.ElapsedMS + 1160
		count := 2
		if game.randomBetween(0, 1) < .2 {
			count = 3
		}
		for range count {
			game.addCoin(game.randomBetween(35, Width-35), game.randomBetween(35, Height-35))
		}
	}
	if game.ElapsedMS >= game.ItemAt && len(game.Items) < 2 {
		game.ItemAt = game.ElapsedMS + int64(game.randomBetween(7000, 11000))
		types := [...]string{"magnet", "smoke", "double"}
		game.Items = append(game.Items, Item{
			X: game.randomBetween(45, Width-45), Y: game.randomBetween(45, Height-45), R: 12,
			Type: types[int(game.randomBetween(0, 3))], Phase: game.randomBetween(0, 7), Life: 10,
		})
	}
	seconds := float64(game.ElapsedMS) / 1000
	for i := range game.Patrols {
		patrol := &game.Patrols[i]
		wave := math.Sin(seconds*patrol.Speed + patrol.Phase)
		if patrol.Axis == "x" {
			patrol.X = patrol.Center + wave*patrol.Range
			patrol.Y = 145 + math.Mod(patrol.Phase*57, 270)
		} else {
			patrol.Y = patrol.Center + wave*patrol.Range
			patrol.X = 140 + math.Mod(patrol.Phase*139, 620)
		}
	}
	alive := game.Coins[:0]
	for _, coin := range game.Coins {
		proximity := math.Hypot(coin.X-game.Player.X, coin.Y-game.Player.Y)
		if game.MagnetT > 0 && proximity < 110 {
			divisor := max(1, proximity)
			coin.X += (game.Player.X - coin.X) / divisor * 220 * dt
			coin.Y += (game.Player.Y - coin.Y) / divisor * 220 * dt
			proximity = math.Hypot(coin.X-game.Player.X, coin.Y-game.Player.Y)
		}
		radius := game.Player.R + coin.R
		if game.MagnetT > 0 {
			radius += 5
		}
		if proximity >= radius || (distance <= 9 && game.MagnetT <= 0) {
			alive = append(alive, coin)
			continue
		}
		game.CoinsCollected++
		if game.ElapsedMS < game.ComboUntil {
			game.Combo++
		} else {
			game.Combo = 1
		}
		game.ComboUntil = game.ElapsedMS + 2500
		base := 10.0
		if coin.Value == 3 {
			base = 50
		}
		bonus := 1.0
		if game.MagnetT > 0 {
			bonus = 1.25
		}
		points := int(math.Round(base * game.Multiplier() * bonus))
		previous := game.Score
		game.Score = min(MaxScore, game.Score+points)
		game.NoticePoints = game.Score - previous
		game.Notice, game.NoticeT = "points", .9
	}
	game.Coins = alive
	remaining := game.Items[:0]
	for _, item := range game.Items {
		item.Life -= dt
		if item.Life <= 0 {
			continue
		}
		if math.Hypot(item.X-game.Player.X, item.Y-game.Player.Y) >= game.Player.R+item.R+5 {
			remaining = append(remaining, item)
			continue
		}
		switch item.Type {
		case "magnet":
			game.MagnetT = 6
		case "smoke":
			game.SmokeT = 5
		case "double":
			game.MultT = 6
		}
		game.Notice, game.NoticeT = item.Type, .9
	}
	game.Items = remaining
	for _, patrol := range game.Patrols {
		if math.Hypot(patrol.X-game.Player.X, patrol.Y-game.Player.Y) < patrol.R+game.Player.R+5 && game.Player.Inv <= 0 && game.SmokeT <= 0 {
			game.CaughtT, game.Player.Inv = .7, 1.1
			game.Combo, game.ComboUntil = 0, 0
			game.Notice, game.NoticeT = "caught", 1.2
		}
	}
}
